# Exercise 2: Ayah Formatter
# Store this ayah: "bismillah ar-rahman ar-rahim"
# Print it:
# - In title case
# - All uppercase
# - With proper Arabic transliteration capitalization
# Your code here:

ayah = "bismillah ar-rahman ar-rahim"

# In title case
print(ayah.title())

# All uppercase
print(ayah.upper())

# Proper Arabic transliteration capitalization
proper_transliteration = "Bismillah ar-Rahman ar-Rahim"
print(proper_transliteration)
