# Exercise 17: Negative Indexing
# Create a list of 7 days of the week
# Print:
# - Last day
# - Second to last day
# - Last 3 days
# All using negative indices
# Your code here:
Days = ['Sunday', "Monday", 'Tuesday', 'Wednesday', 'Thursday', 'Friday', "Saturday"]
print(f"Last day: {Days[-1]}")
print(f"Second to last day: {Days[-2]}")
print(f"Last 3 days: {Days[-3:]}")